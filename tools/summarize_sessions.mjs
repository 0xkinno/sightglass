// summarize_sessions.mjs
// Counts Claude Code sessions, minutes and Lens Studio MCP tool calls for this project from the local session logs
// and writes devpost/BUILD_LOG.md. Counts come from the logs, never typed by hand.
// Usage: node tools/summarize_sessions.mjs
import fs from "node:fs"
import path from "node:path"
import os from "node:os"

const dir = path.join(os.homedir(), ".claude", "projects", "C--Users-hp-OneDrive-Documents-Sightglass")
const rows = []
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".jsonl"))) {
  let first = null
  let last = null
  let lens = 0
  const names = {}
  for (const line of fs.readFileSync(path.join(dir, f), "utf8").split("\n")) {
    if (!line.trim()) continue
    let o
    try {
      o = JSON.parse(line)
    } catch {
      continue
    }
    if (o.timestamp) {
      const t = Date.parse(o.timestamp)
      if (first === null || t < first) first = t
      if (last === null || t > last) last = t
    }
    const content = o.message && Array.isArray(o.message.content) ? o.message.content : []
    for (const c of content) {
      if (c.type === "tool_use" && /^mcp__lens[-_]studio__/i.test(c.name || "")) {
        lens++
        const short = c.name.replace(/^mcp__lens[-_]studio__/i, "")
        names[short] = (names[short] || 0) + 1
      }
    }
  }
  if (first !== null) rows.push({id: f.replace(".jsonl", "").slice(0, 8), minutes: Math.round((last - first) / 60000), lens, names})
}
const total = rows.reduce((s, r) => s + r.lens, 0)
const mins = rows.reduce((s, r) => s + r.minutes, 0)
const byTool = {}
for (const r of rows) for (const [k, v] of Object.entries(r.names)) byTool[k] = (byTool[k] || 0) + v
const md = [
  "# BUILD LOG",
  "",
  "Generated by `tools/summarize_sessions.mjs` from the local Claude Code session logs for this project. Nothing here is typed by hand.",
  "Minutes are the span between the first and last message of a session, so a session left open overnight counts all of it.",
  "",
  `Sessions: ${rows.length}. Session minutes: ${mins}. Lens Studio MCP tool calls: ${total}.`,
  "",
  "| Session | Minutes | Lens Studio MCP calls |",
  "|---|---:|---:|",
  ...rows.sort((a, b) => b.lens - a.lens).map((r) => `| ${r.id} | ${r.minutes} | ${r.lens} |`),
  "",
  "## Lens Studio MCP calls by tool",
  "",
  "| Tool | Calls |",
  "|---|---:|",
  ...Object.entries(byTool).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`),
  "",
].join("\n")
fs.writeFileSync("devpost/BUILD_LOG.md", md)
console.log(`sessions ${rows.length} minutes ${mins} lens calls ${total}`)
