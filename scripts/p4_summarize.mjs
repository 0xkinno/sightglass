// p4_summarize.mjs
// Reads devpost/evidence/preview-reads.log (SIGHTGLASS_ACC and SIGHTGLASS_RAW lines copied from the Lens Studio log)
// and prints per-gauge and per-arm statistics. Also writes the recorded fixtures: the first "hide" arm reply per gauge
// goes to Assets/Tests/fixtures/<gauge>.json and Assets/Tests/fixtures/Fixtures.ts.
// Usage: node scripts/p4_summarize.mjs [--write-fixtures]
import fs from "node:fs"

const log = fs.readFileSync("devpost/evidence/preview-reads.log", "utf8").split("\n")
const acc = []
const raws = []
for (const l of log) {
  if (l.startsWith("SIGHTGLASS_ACC arm=")) {
    const o = {}
    for (const m of l.matchAll(/(\w+)=(\S+)/g)) o[m[1]] = m[2]
    acc.push(o)
  } else if (l.startsWith("SIGHTGLASS_RAW ")) {
    raws.push(l)
  }
}
const num = (v) => (v === undefined || v === "null" ? null : Number(v))
const stat = (xs) => {
  const a = xs.filter((x) => x !== null).sort((p, q) => p - q)
  if (!a.length) return null
  const mean = a.reduce((s, x) => s + x, 0) / a.length
  const med = a[Math.floor(a.length / 2)]
  return {n: a.length, mean: +mean.toFixed(2), median: +med.toFixed(2), max: +a[a.length - 1].toFixed(2)}
}
const out = {perArm: {}, perGauge: {}}
for (const arm of ["hide", "show"]) {
  const rows = acc.filter((r) => r.arm === arm && !r.skipped)
  const legible = rows.filter((r) => r.expectCant !== "true")
  const read = legible.filter((r) => r.kind !== "CANT_READ")
  const absErr = read.map((r) => Math.abs(num(r.errTicks)))
  out.perArm[arm] = {
    captures: rows.length,
    legibleCaptures: legible.length,
    read: read.length,
    cantReadOnLegible: legible.length - read.length,
    absErrTicks: stat(absErr),
    within1Tick: absErr.filter((e) => e <= 1).length,
    within2Ticks: absErr.filter((e) => e <= 2).length,
    ms: stat(rows.map((r) => num(r.ms))),
  }
  const fog = rows.filter((r) => r.expectCant === "true")
  out.perArm[arm].fogged = {captures: fog.length, cantRead: fog.filter((r) => r.kind === "CANT_READ").length, readAValue: fog.filter((r) => r.kind !== "CANT_READ").length}
}
const gauges = [...new Set(acc.map((r) => r.gauge))]
for (const g of gauges) {
  const rows = acc.filter((r) => r.gauge === g && r.arm === "hide" && !r.skipped)
  const reads = rows.filter((r) => r.kind !== "CANT_READ")
  out.perGauge[g] = {
    captures: rows.length,
    cantRead: rows.length - reads.length,
    absErrTicks: stat(reads.map((r) => Math.abs(num(r.errTicks)))),
    signedMeanTicks: reads.length ? +(reads.reduce((s, r) => s + num(r.errTicks), 0) / reads.length).toFixed(2) : null,
    modelValueAbsErrTicks: stat(rows.map((r) => (num(r.modelValue) === null ? null : Math.abs((num(r.modelValue) - num(r.truth)) / num(r.minorTick))))),
  }
}
out.skipped = acc.filter((r) => r.skipped).length
console.log(JSON.stringify(out, null, 2))

if (process.argv.includes("--write-fixtures")) {
  fs.mkdirSync("Assets/Tests/fixtures", {recursive: true})
  const rec = {}
  for (const g of gauges) {
    const line = raws.find((l) => l.startsWith("SIGHTGLASS_RAW gauge=" + g + " "))
    if (!line) continue
    const json = line.split(" json=")[1]
    JSON.parse(json)
    fs.writeFileSync("Assets/Tests/fixtures/" + g + ".json", json + "\n")
    rec[g] = json
  }
  const sm = log.map((l) => /SIGHTGLASS_READ .*stretchX=([0-9.]+)/.exec(l)).filter((m) => m)[0]
  const stretch = sm ? Number(sm[1]) : 1
  const ts =
    "// Fixtures.ts\n// Recorded live reader responses, one per gauge, copied from SIGHTGLASS_RAW log lines of the preview run in\n// devpost/evidence/preview-reads.log. Generated by scripts/p4_summarize.mjs --write-fixtures. Do not edit by hand.\n" +
    "export const RECORDED: {[gaugeId: string]: string} = " + JSON.stringify(rec, null, 2) + "\n" +
    "// Horizontal squash of the composite when these were recorded. replay mode divides x by this, as live mode does.\nexport const RECORDED_STRETCH = " + stretch + "\n"
  fs.writeFileSync("Assets/Tests/fixtures/Fixtures.ts", ts)
  console.log("fixtures written: " + Object.keys(rec).join(", "))
}
